class Solution {
public:
    string maximumTime(string time) {
        // หลักที่ 0: ชั่วโมงหลักสิบ
        if (time[0] == '?') {
            // ถ้าชั่วโมงหลักหน่วยเป็น ? หรือ ≤ 3 → ใส่ 2 ได้
            if (time[1] == '?' || time[1] <= '3') {
                time[0] = '2';
            } else {
                time[0] = '1';
            }
        }
        
        // หลักที่ 1: ชั่วโมงหลักหน่วย
        if (time[1] == '?') {
            // ถ้าชั่วโมงหลักสิบเป็น 2 → ใส่ได้สูงสุด 3
            if (time[0] == '2') {
                time[1] = '3';
            } else {
                time[1] = '9';
            }
        }
        
        // หลักที่ 3: นาทีหลักสิบ
        if (time[3] == '?') {
            time[3] = '5';
        }
        
        // หลักที่ 4: นาทีหลักหน่วย
        if (time[4] == '?') {
            time[4] = '9';
        }
        
        return time;
    }
};