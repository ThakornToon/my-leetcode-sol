impl Solution {
    pub fn max_envelopes(envelopes: Vec<Vec<i32>>) -> i32 {
        let mut envelopes = envelopes;
        
        // เรียงลำดับ envelopes
        envelopes.sort_by(|a, b| {
            if a[0] == b[0] {
                b[1].cmp(&a[1]) // เรียง height จากมากไปน้อยเมื่อ width เท่ากัน
            } else {
                a[0].cmp(&b[0]) // เรียง width จากน้อยไปมาก
            }
        });
        
        // หา LIS บน height
        let mut lis = Vec::new();
        for env in envelopes {
            let h = env[1];
            match lis.binary_search(&h) {
                Ok(_) => {}, // ถ้าพบค่าเดียวกัน ไม่ทำอะไร
                Err(pos) => {
                    if pos == lis.len() {
                        lis.push(h);
                    } else {
                        lis[pos] = h;
                    }
                }
            }
        }
        
        lis.len() as i32
    }
}

