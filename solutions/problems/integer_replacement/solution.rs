/*
เลขคู่: ใช้การ shift ขวา 1 ครั้ง (>> 1) แทนการหารด้วย 2
เลขคี่: ตรวจสอบบิตเพื่อตัดสินใจว่าจะบวกหรือลบ 1:
กรณีพิเศษ: ถ้า n = 3 ให้ลดค่า (เพราะ 3 → 2 → 1 ดีกว่า 3 → 4 → 2 → 1)
เมื่อบิต 2 ตัวสุดท้ายเป็น 11 (n % 4 == 3): ให้บวก 1
อื่นๆ: ให้ลบ 1

ทำไมถึงใช้กฎนี้?
การบวก 1 เมื่อบิตลงท้ายเป็น 11 จะทำให้ได้เลขคู่ที่หารด้วย 4 ลงตัว
การลบ 1 เมื่อบิตลงท้ายเป็น 01 จะทำให้ได้เลขคู่ที่หารด้วย 2 ลงตัว
*/
impl Solution {
    pub fn integer_replacement(n: i32) -> i32 {
        let mut steps = 0;
        let mut num = n as i64;  // ใช้ i64 เพื่อป้องกัน overflow
        
        while num != 1 {
            if num % 2 == 0 {
                // เลขคู่: shift ขวา 1 บิต
                num >>= 1;
            } else {
                if num == 3 {
                    // กรณีพิเศษ: 3 → 2 → 1
                    num -= 1;
                } else if (num & 3) == 3 {
                    // 2 บิตสุดท้ายเป็น 11: บวก 1
                    num += 1;
                } else {
                    // กรณีอื่น: ลบ 1
                    num -= 1;
                }
            }
            steps += 1;
        }
        
        steps
    }
}